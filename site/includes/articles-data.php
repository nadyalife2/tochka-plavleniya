/**
 * Получить статью по slug
 */
function get_article_by_slug(string $slug): ?array {
  global $articles;
  foreach ($articles as $a) {
    if ($a['slug'] === $slug) return $a;
  }
  return null;
}

/**
 * Получить статьи по тегу
 */
function get_articles_by_tag(string $tag_key): array {
  global $articles;
  return array_filter($articles, fn($a) => $a['tag_key'] === $tag_key);
}

/**
 * Получить featured-статьи
 */
function get_featured_articles(): array {
  global $articles;
  return array_filter($articles, fn($a) => $a['featured'] === true);
}
