/**
 * Возвращает правило подбора флюса
 */
function get_flux_recommendation(string $metal, string $process, string $wash): ?array {
    global $FLUX_RULES;
    return $FLUX_RULES[$metal][$process][$wash] ?? null;
}

/**
 * Возвращает узел дерева по id.
 */
function get_defect_node(string $id): ?array {
    global $DEFECT_TREE;
    return $DEFECT_TREE[$id] ?? null;
}

/**
 * Метка критичности на русском.
 */
function defect_severity_label(string $severity): string {
    return match($severity) {
        'low'    => 'Норма / Некритично',
        'medium' => 'Требует технологической коррекции',
        'high'   => 'Критический дефект / Нарушение ТБ',
        default  => $severity,
    };
}

/**
 * CSS-класс критичности.
 */
function defect_severity_class(string $severity): string {
    return match($severity) {
        'low'    => 'severity-low',
        'medium' => 'severity-medium',
        'high'   => 'severity-high',
        default  => '',
    };
}
