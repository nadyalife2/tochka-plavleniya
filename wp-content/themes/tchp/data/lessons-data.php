/**
 * Хелпер для поиска микроурока по slug
 */
function get_lesson_by_slug(string $slug): ?array {
    global $lessons;
    return $lessons[$slug] ?? null;
}

/**
 * Хелпер для получения всех микроуроков
 */
function get_all_lessons(): array {
    global $lessons;
    return array_values($lessons);
}
